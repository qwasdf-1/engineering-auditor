macro_rules! halstead_token_set {
    ($kind:expr, $($token:literal)|+ $(,)?) => {{
        static TOKENS: std::sync::LazyLock<std::collections::HashSet<&'static str>> =
            std::sync::LazyLock::new(|| std::collections::HashSet::from([$($token),+]));
        TOKENS.contains($kind)
    }};
}


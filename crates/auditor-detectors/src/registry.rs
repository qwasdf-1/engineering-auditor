pub(crate) fn detector_catalog(
    profile: ScanProfile,
) -> impl Iterator<Item = &'static DetectorSpec> {
    catalog_specs().filter(move |spec| profile.includes(spec.minimum_profile))
}

/// Every catalog entry: the core table, then the v1.0 families.
pub(crate) fn catalog_specs() -> impl Iterator<Item = &'static DetectorSpec> {
    DETECTOR_CATALOG.iter().chain(families::FAMILY_CATALOG)
}

pub(crate) fn detector_spec(id: &str) -> Option<&'static DetectorSpec> {
    catalog_specs().find(|spec| spec.id == id)
}

pub(crate) fn detector_supports_language(id: &str, language: &crate::Language) -> bool {
    supports_language(support_policy_for(id), language)
}


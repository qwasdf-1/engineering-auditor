macro_rules! spec {
    ($id:literal, $category:literal, $severity:ident, $profile:ident, $layer:literal, $owner:ident) => {
        DetectorSpec {
            id: $id,
            category: $category,
            default_severity: Severity::$severity,
            minimum_profile: ScanProfile::$profile,
            layer: $layer,
            owner: DetectorOwner::$owner,
            role_applicability: RoleApplicability::Code,
            context_applicability: RoleApplicability::Code,
            full_profile_languages: &[],
        }
    };
}


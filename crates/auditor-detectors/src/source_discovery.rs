pub const SOURCE_ROLE_VERSION: u32 = 1;

#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub enum SourceRole {
    Production,
    Tooling,
    Test,
    Fixture,
    Benchmark,
    Example,
    Generated,
    Documentation,
    Reference,
}

impl SourceRole {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Production => "production",
            Self::Tooling => "tooling",
            Self::Test => "test",
            Self::Fixture => "fixture",
            Self::Benchmark => "benchmark",
            Self::Example => "example",
            Self::Generated => "generated",
            Self::Documentation => "documentation",
            Self::Reference => "reference",
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq, Ord, PartialOrd)]
pub enum Language {
    Rust,
    Python,
    JavaScript,
    TypeScript,
    Go,
    Java,
    Kotlin,
    CSharp,
    C,
    Cpp,
    Ruby,
    Julia,
    Markdown,
    Json,
    Toml,
    Yaml,
    Shell,
    Other(String),
}

impl Language {
    pub fn as_str(&self) -> &str {
        match self {
            Self::Rust => "rust",
            Self::Python => "python",
            Self::JavaScript => "javascript",
            Self::TypeScript => "typescript",
            Self::Go => "go",
            Self::Java => "java",
            Self::Kotlin => "kotlin",
            Self::CSharp => "csharp",
            Self::C => "c",
            Self::Cpp => "cpp",
            Self::Ruby => "ruby",
            Self::Julia => "julia",
            Self::Markdown => "markdown",
            Self::Json => "json",
            Self::Toml => "toml",
            Self::Yaml => "yaml",
            Self::Shell => "shell",
            Self::Other(value) => value.as_str(),
        }
    }

    pub fn is_source(&self) -> bool {
        self.is_tiered() || matches!(self, Self::Ruby | Self::Julia | Self::Shell)
    }

    /// A Tier-1 or Tier-2 language: the ten with full AST detector coverage.
    pub fn is_tiered(&self) -> bool {
        matches!(
            self,
            Self::Rust
                | Self::Python
                | Self::JavaScript
                | Self::TypeScript
                | Self::Go
                | Self::Java
                | Self::Kotlin
                | Self::CSharp
                | Self::C
                | Self::Cpp
        )
    }

    pub fn catalog_key(&self) -> &str {
        match self {
            Self::Json | Self::Toml | Self::Yaml => "structured",
            other => other.as_str(),
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SourceFile {
    pub path: PathBuf,
    pub language: Language,
    pub bytes: u64,
    pub role: SourceRole,
}

#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum AnalysisMethod {
    #[default]
    Auto,
    Ast,
    Token,
}

impl AnalysisMethod {
    pub fn parse(value: &str) -> Result<Self, String> {
        match value {
            "auto" => Ok(Self::Auto),
            "ast" => Ok(Self::Ast),
            "token" => Ok(Self::Token),
            _ => Err("analysis method requires auto|ast|token".to_string()),
        }
    }

    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Auto => "auto",
            Self::Ast => "ast",
            Self::Token => "token",
        }
    }
}

#[derive(Clone, Copy, Debug, Default)]
pub struct SourceDiscoveryOptions {
    pub include_references: bool,
    pub method: AnalysisMethod,
}

#[derive(Clone, Debug)]
pub(crate) struct AuditedFile {
    pub(crate) absolute: PathBuf,
    pub(crate) relative: PathBuf,
    pub(crate) language: Language,
    pub(crate) bytes: u64,
    pub(crate) role: SourceRole,
}

pub fn discover_sources(
    root: &Path,
    options: SourceDiscoveryOptions,
) -> io::Result<Vec<SourceFile>> {
    discover_sources_with_filter(root, options, &ScopeFilter::default())
}

pub fn discover_sources_with_filter(
    root: &Path,
    options: SourceDiscoveryOptions,
    filter: &ScopeFilter,
) -> io::Result<Vec<SourceFile>> {
    Ok(discover_audited_files_with_filter(root, options, filter)?
        .into_iter()
        .map(|file| SourceFile {
            path: file.relative,
            language: file.language,
            bytes: file.bytes,
            role: file.role,
        })
        .collect())
}

pub(crate) fn discover_audited_files_with_filter(
    root: &Path,
    options: SourceDiscoveryOptions,
    filter: &ScopeFilter,
) -> io::Result<Vec<AuditedFile>> {
    let mut files = Vec::new();
    let filter_root = root.to_path_buf();
    let mut walker = ignore::WalkBuilder::new(root);
    walker
        .add_custom_ignore_filename(IGNORE_FILENAME)
        .hidden(false)
        .parents(false)
        .git_global(false)
        .git_exclude(false)
        .require_git(false)
        .filter_entry(move |entry| {
            !entry
                .file_type()
                .is_some_and(|file_type| file_type.is_dir())
                || !should_skip_dir(&filter_root, entry.path(), options)
        });
    for entry in walker.build() {
        let entry = entry.map_err(ignore_error)?;
        if entry.depth() == 0
            || !entry
                .file_type()
                .is_some_and(|file_type| file_type.is_file())
        {
            continue;
        }
        let path = entry.into_path();
        if is_excluded_path(root, &path, options) {
            continue;
        }
        if path.starts_with(root) {
            let rel = util::relative_slash(root, &path);
            if !filter.matches(&rel) {
                continue;
            }
        }
        let bytes = fs::metadata(&path)?.len();
        files.extend(audited_file(root, path, bytes));
    }
    files.sort_by(|a, b| a.relative.cmp(&b.relative));
    crate::rust_test_modules::mark_rust_test_modules(&mut files);
    Ok(files)
}

/// A discovered path as an audited file: a source in its language and role,
/// or a transient build artifact; `None` for anything else.
fn audited_file(root: &Path, path: PathBuf, bytes: u64) -> Option<AuditedFile> {
    let relative = path.strip_prefix(root).unwrap_or(&path).to_path_buf();
    let Some(language) = language_for_path(&path) else {
        transient_artifact_kind(root, &path)?;
        return Some(AuditedFile {
            absolute: path,
            relative,
            language: Language::Other("artifact".to_string()),
            bytes,
            role: SourceRole::Generated,
        });
    };
    let language = if language == Language::C && header_is_cpp(&path) {
        Language::Cpp
    } else {
        language
    };
    let role = match source_role_for_path(&relative) {
        SourceRole::Production if language != Language::Markdown && is_generated_output(&path) => {
            SourceRole::Generated
        }
        role => role,
    };
    Some(AuditedFile {
        absolute: path,
        relative,
        language,
        bytes,
        role,
    })
}

/// Bounded path filter applied during source discovery.
///
/// An empty filter (the default) is a no-op: every discovered file passes.
/// A non-empty filter retains only files whose relative path appears in
/// `paths`; line ranges are honored when present for the matching path.
/// Discovery is pruned so a `ScanScope::Changed` invocation does not pay
/// the cost of walking the whole repository before the scope filter
/// would have culled the result set.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct ScopeFilter {
    paths: std::collections::BTreeSet<String>,
    ranges: Vec<crate::ChangedRange>,
}

impl ScopeFilter {
    pub fn new(
        paths: std::collections::BTreeSet<String>,
        ranges: Vec<crate::ChangedRange>,
    ) -> Self {
        Self { paths, ranges }
    }

    pub fn is_empty(&self) -> bool {
        self.paths.is_empty() && self.ranges.is_empty()
    }

    /// Returns `true` when the relative path is permitted by the filter.
    pub fn matches(&self, relative: &str) -> bool {
        if self.is_empty() {
            return true;
        }
        if !self.paths.contains(relative) {
            return false;
        }
        let has_range = self.ranges.iter().any(|range| range.path == relative);
        // A path-only scope (no ranges) keeps every file in `paths`.
        // A path-with-ranges scope keeps the file when any range names
        // the same path; the line-bounded check happens later in
        // `finding_matches_changed_scope` against emitted findings.
        !has_range || self.ranges.iter().any(|range| range.path == relative)
    }
}

fn ignore_error(error: ignore::Error) -> io::Error {
    io::Error::other(error)
}

fn should_skip_dir(root: &Path, path: &Path, options: SourceDiscoveryOptions) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    if SKIP_DIR_NAMES.contains(&name) {
        return true;
    }
    let rel = util::relative_slash(root, path);
    if !options.include_references && (rel == "references" || rel.starts_with("references/")) {
        return true;
    }
    let is_archive = |r: &str| {
        SKIP_DIR_PREFIXES
            .iter()
            .any(|p| r == p.trim_end_matches('/') || r.starts_with(p))
    };
    is_archive(&rel)
}

fn is_excluded_path(root: &Path, path: &Path, options: SourceDiscoveryOptions) -> bool {
    let rel = util::relative_slash(root, path);
    if !options.include_references && (rel == "references" || rel.starts_with("references/")) {
        return true;
    }
    EXCLUDED_PATH_PREFIXES.iter().any(|p| rel.starts_with(p)) || is_managed_audit_artifact(path)
}

fn is_managed_audit_artifact(path: &Path) -> bool {
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_default();
    (name.contains(".repository-map.") || name.contains(".engineering-review."))
        && (name.ends_with(".json") || name.ends_with(".tmp"))
}

pub fn source_role_for_path(path: &Path) -> SourceRole {
    let original = path
        .components()
        .filter_map(|component| component.as_os_str().to_str())
        .collect::<Vec<_>>();
    let components = original
        .iter()
        .map(|component| component.to_ascii_lowercase())
        .collect::<Vec<_>>();
    let name = components.last().map(String::as_str).unwrap_or_default();
    let stem = Path::new(name)
        .file_stem()
        .and_then(|value| value.to_str())
        .unwrap_or(name);
    let role = ordered_source_roles(&components, &original, name, stem)
        .find_map(|(role, matches)| matches.then_some(role))
        .unwrap_or(SourceRole::Production);
    role
}

fn is_generated_name(name: &str, stem: &str) -> bool {
    name.contains(".generated.") || stem.ends_with("_generated")
}

/// `bench_x`, `x_bench`, or JMH's `ParseBenchmark.java`.
fn is_benchmark_stem(stem: &str) -> bool {
    stem.starts_with("bench_")
        || stem.ends_with("_bench")
        || stem.ends_with("benchmark")
        || stem.ends_with("benchmarks")
}

fn is_test_file(components: &[String], original: &[&str], stem: &str) -> bool {
    is_test_stem(stem)
        || is_test_project(original)
        || is_test_class_file(original)
        || top_level_directory(components, "integration")
}

/// Build files, and a repository-root `build/` or `support/` (fmt's release
/// and generator scripts), `extra/` (uptime-kuma's release and maintenance
/// scripts), or `hack/` (Kubernetes-style development scripts). Nested
/// directories of those names are code.
fn is_build_path(components: &[String], name: &str) -> bool {
    is_build_file(name)
        || ["build", "support", "extra", "hack"]
            .iter()
            .any(|directory| top_level_directory(components, directory))
}

fn ordered_source_roles<'a>(
    components: &'a [String],
    original: &'a [&'a str],
    name: &'a str,
    stem: &'a str,
) -> impl Iterator<Item = (SourceRole, bool)> + 'a {
    // A `tools` or `scripts` package (`tools.jackson.core`) is not a tooling
    // directory; `examples` and `test` packages do mean what they say.
    let layout = layout_components(components);
    [
        (
            SourceRole::Reference,
            has_component(components, REFERENCE_COMPONENTS),
        ),
        (
            SourceRole::Generated,
            has_component(components, GENERATED_COMPONENTS) || is_generated_name(name, stem),
        ),
        (
            SourceRole::Fixture,
            has_component(components, FIXTURE_COMPONENTS) || stem.starts_with("capability_cases_"),
        ),
        (
            SourceRole::Benchmark,
            has_component(components, BENCHMARK_COMPONENTS) || is_benchmark_stem(stem),
        ),
        (
            SourceRole::Test,
            has_component(components, TEST_COMPONENTS) || is_test_file(components, original, stem),
        ),
        (
            SourceRole::Example,
            has_component(components, EXAMPLE_COMPONENTS)
                // A named example set (`extra/push-examples/`).
                || components[..components.len().saturating_sub(1)]
                    .iter()
                    .any(|component| component.ends_with("-examples"))
                || stem.starts_with("example_")
                || stem.ends_with("_example"),
        ),
        (
            SourceRole::Tooling,
            has_component(layout, TOOLING_COMPONENTS) || is_build_path(components, name),
        ),
        (
            SourceRole::Documentation,
            is_documentation_path(components, name),
        ),
    ]
    .into_iter()
}

/// Build scripts and tool configuration (lower-cased names):
/// `eslint.config.js`, `build.gradle.kts`, `Makefile.js`.
fn is_build_file(name: &str) -> bool {
    const TASK_RUNNERS: &[&str] = &["gulpfile.", "gruntfile.", "makefile.", "jakefile."];
    const GRADLE: &[&str] = &[
        "build.gradle",
        "build.gradle.kts",
        "settings.gradle",
        "settings.gradle.kts",
    ];
    const CONFIGURED_TOOLS: &[&str] = &[
        "babel",
        "docusaurus",
        "esbuild",
        "eslint",
        "jest",
        "karma",
        "playwright",
        "postcss",
        "prettier",
        "rollup",
        "stylelint",
        "tailwind",
        "tsdown",
        "tsup",
        "vite",
        "vitest",
        "webpack",
    ];
    TASK_RUNNERS.iter().any(|prefix| name.starts_with(prefix))
        || GRADLE.contains(&name)
        || name
            .split_once(".config.")
            .is_some_and(|(tool, _)| CONFIGURED_TOOLS.contains(&tool))
}

/// Matches a path component, also wrapped in `_` (`_examples`, the Go
/// convention for directories the toolchain skips, or `__performance_tests__`).
/// A repository-root directory whose name is only conventional there: a
/// root `build/` holds build scripts and a root `integration/` holds
/// integration tests (hono, fastify), while a nested `build` or
/// `integration` package can be the project's own code.
fn top_level_directory(components: &[String], directory: &str) -> bool {
    components.len() > 1 && components[0] == directory
}

fn has_component(components: &[String], candidates: &[&str]) -> bool {
    components.iter().any(|component| {
        candidates.contains(&component.as_str())
            || candidates.contains(&component.trim_matches('_'))
    })
}

fn is_test_stem(stem: &str) -> bool {
    matches!(stem, "test" | "tests")
        || stem.starts_with("test_")
        || stem.starts_with("test-")
        || [
            "_test",
            "_tests",
            "_parity",
            "_test_support",
            ".test",
            ".spec",
        ]
        .iter()
        .any(|suffix| stem.ends_with(suffix))
}

fn is_documentation_path(components: &[String], name: &str) -> bool {
    components.first().is_some_and(|item| item == "docs")
        || Path::new(name)
            .extension()
            .and_then(|value| value.to_str())
            .is_some_and(|extension| DOCUMENTATION_EXTENSIONS.contains(&extension))
        || DOCUMENTATION_NAMES.contains(&name)
}

pub fn language_for_path(path: &Path) -> Option<Language> {
    let file_name = path
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_default();
    if matches!(file_name, "Cargo.toml" | "pyproject.toml") {
        return Some(Language::Toml);
    }
    let extension = path.extension().and_then(|ext| ext.to_str())?;
    EXTENSION_LANGUAGES
        .iter()
        .find_map(|(candidate, language)| (*candidate == extension).then(|| language.clone()))
}

fn transient_artifact_kind(root: &Path, path: &Path) -> Option<&'static str> {
    let rel = util::relative_slash(root, path);
    if rel.ends_with(".orig") || rel.ends_with(".rej") {
        return Some("merge_scratch");
    }
    if rel.ends_with(".pyc") || rel.contains("__pycache__/") {
        return Some("python_cache");
    }
    if rel.starts_with("docs/diagnostics/") {
        return Some("diagnostic_under_docs");
    }
    None
}

pub(crate) fn generated_vs_source_findings(files: &[AuditedFile]) -> Vec<Finding> {
    files
        .iter()
        .filter_map(|file| {
            let root = file.absolute.parent()?;
            let kind = transient_artifact_kind(root, &file.absolute)
                .or_else(|| transient_artifact_kind(Path::new(""), &file.relative))?;
            let rel = util::path_slash(&file.relative);
            let message = match kind {
                "merge_scratch" => "Merge scratch file is present in the worktree.",
                "python_cache" => "Python bytecode/cache artifact is present in the worktree.",
                _ => "Transient diagnostic evidence is stored under docs.",
            };
            Some(
                auditor_core::finding!(
                    "generated_vs_source",
                    "generated_vs_source",
                    "Generated or transient artifact in audited tree",
                    message,
                    if kind == "diagnostic_under_docs" {
                        Severity::Medium
                    } else {
                        Severity::High
                    },
                    Confidence::High,
                    rel,
                    None,
                )
                .with_recommendation(
                    "Delete transient output or move durable evidence into the trace store.",
                )
                .with_evidence("kind", kind),
            )
        })
        .collect()
}

